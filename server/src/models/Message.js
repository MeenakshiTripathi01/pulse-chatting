import mongoose from 'mongoose';

const { ObjectId } = mongoose.Schema.Types;

export const MESSAGE_MAX_LENGTH = 2000;

// Snapshot of the message being replied to, so a thread can render quotes without loading
// the original. If the original is deleted, `content` is removed and `deleted` is set.
const replyToSchema = new mongoose.Schema(
  {
    messageId: { type: ObjectId, ref: 'Message', required: true },
    sender: { type: ObjectId, ref: 'User', required: true },
    content: { type: String },
    deleted: { type: Boolean, default: false },
  },
  { _id: false },
);

const messageSchema = new mongoose.Schema(
  {
    conversation: { type: ObjectId, ref: 'Conversation', required: true },
    sender: { type: ObjectId, ref: 'User', required: true },
    // Removed when the sender deletes the message for everyone.
    content: {
      type: String,
      required() {
        return !this.deletedAt;
      },
      trim: true,
      maxlength: MESSAGE_MAX_LENGTH,
    },
    replyTo: { type: replyToSchema, default: null },
    deletedAt: { type: Date, default: null },
    // Random id generated by the sending browser. If a send is retried (e.g. after a network
    // hiccup) the server recognises the id and returns the original message instead of
    // storing a duplicate.
    clientMessageId: { type: String, maxlength: 64 },
  },
  // Messages can't be edited, only deleted (tracked by deletedAt), so only createdAt is kept.
  { timestamps: { createdAt: true, updatedAt: false } },
);

// Loading a page of history: filter by conversation, sort newest first.
// _id is included as a tie-breaker for messages created in the same millisecond.
messageSchema.index({ conversation: 1, createdAt: -1, _id: -1 });
// Idempotency: the same sender cannot store two messages with the same client id.
messageSchema.index(
  { sender: 1, clientMessageId: 1 },
  { unique: true, partialFilterExpression: { clientMessageId: { $type: 'string' } } },
);
// Finding the replies that quote a message when it is deleted.
messageSchema.index(
  { 'replyTo.messageId': 1 },
  { partialFilterExpression: { 'replyTo.messageId': { $exists: true } } },
);

export const Message = mongoose.model('Message', messageSchema);
